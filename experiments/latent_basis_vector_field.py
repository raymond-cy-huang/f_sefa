parse_gan_type = None
factorize_weight = None
load_generator = None
postprocess = None
to_tensor = None


def parse_args():
    parser = argparse.ArgumentParser(description="Explicit basis semantic vector-field traversal.")
    parser.add_argument("--model", default="stylegan_animeface512")
    parser.add_argument("--num_samples", type=int, default=3)
    parser.add_argument("--semantic_id", type=int, default=25)
    parser.add_argument("--num_directions", type=int, default=3)
    parser.add_argument("--layer_idx", default="0-1")
    parser.add_argument("--basis", nargs="+", default=["legendre", "chebyshev", "fourier"])
    parser.add_argument("--basis_order", type=int, default=3)
    parser.add_argument("--projection_scale", type=float, default=3.0)
    parser.add_argument("--step_size", type=float, default=2.0)
    parser.add_argument("--path_steps", type=int, default=5,
                        help="Number of displayed frames per row. Must be odd.")
    parser.add_argument("--output_dir", default="results/basis_vector_field")
    parser.add_argument("--latent_dir", default="latent_codes")
    parser.add_argument("--latent_path", default=None)
    parser.add_argument("--trunc_psi", type=float, default=0.7)
    parser.add_argument("--trunc_layers", type=int, default=8)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--gpu_id", default="0")
    return parser.parse_args()


def _coeff(order):
    coeff = np.zeros(order + 1, dtype=np.float64)
    coeff[order] = 1.0
    return coeff


def basis_derivative(name, x, order):
    """Evaluates d phi_order(x) / dx."""

    name = name.lower()
    x = np.asarray(x, dtype=np.float64)
    coeff = _coeff(order)
    if name == "legendre":
        return legendre.legval(x, legendre.legder(coeff))
    if name == "chebyshev":
        return chebyshev.chebval(x, chebyshev.chebder(coeff))
    if name == "hermite":
        return hermite.hermval(x, hermite.hermder(coeff))
    if name == "laguerre":
        return laguerre.lagval((x + 1.0) * 2.5, laguerre.lagder(coeff)) * 2.5
    if name == "fourier":
        if order <= 0:
            return np.zeros_like(x)
        return np.pi * order * np.cos(np.pi * order * x)
    raise ValueError(f"Unsupported basis `{name}`.")


def generator_device(generator):
    try:
        return next(generator.parameters()).device
    except StopIteration:
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")


def prepare_random_latents(generator, gan_type, num_samples, args):
    z = torch.randn(num_samples, generator.z_space_dim, device=generator_device(generator))
    if gan_type == "pggan":
        return generator.layer0.pixel_norm(z).detach().cpu().numpy().astype(np.float32)
    if gan_type in ["stylegan", "stylegan2", "psp_stylegan2"]:
        w = generator.mapping(z)["w"]
        wp = generator.truncation(w, trunc_psi=args.trunc_psi, trunc_layers=args.trunc_layers)
        return wp.detach().cpu().numpy().astype(np.float32)
    raise ValueError(f"Unsupported GAN type `{gan_type}`.")


def load_or_sample_latents(generator, gan_type, args):
    latent_path = args.latent_path
    if latent_path is None:
        candidate = os.path.join(args.latent_dir, f"{args.model}_latents.npy")
        latent_path = candidate if os.path.exists(candidate) else None

    if latent_path:
        latents = np.load(latent_path).astype(np.float32)
        if latents.ndim == 1:
            latents = latents[None, :]
        elif (
            gan_type in ["stylegan", "stylegan2", "psp_stylegan2"]
            and latents.ndim == 2
            and latents.shape == (generator.num_layers, generator.w_space_dim)
        ):
            latents = latents[None, ...]
        return latents[: args.num_samples], latent_path

    return prepare_random_latents(generator, gan_type, args.num_samples, args), "random"


def to_decoder_code(generator, gan_type, latent):
    latent = np.asarray(latent, dtype=np.float32)
    if gan_type == "pggan":
        return latent.reshape(1, -1)
    if gan_type in ["stylegan", "stylegan2", "psp_stylegan2"]:
        if latent.ndim == 1:
            latent = np.tile(latent[None, :], (generator.num_layers, 1))
        elif latent.ndim == 2 and latent.shape[0] == 1:
            latent = np.tile(latent, (generator.num_layers, 1))
        if latent.ndim != 2 or latent.shape != (generator.num_layers, generator.w_space_dim):
            raise ValueError(
                "StyleGAN latent samples must be [512], [1, 512], or "
                f"[{generator.num_layers}, {generator.w_space_dim}], but got {latent.shape}."
            )
        return latent[None, ...]
    raise ValueError(f"Unsupported GAN type `{gan_type}`.")


def decode_image(generator, gan_type, latent):
    code = to_decoder_code(generator, gan_type, latent)
    with torch.no_grad():
        if gan_type == "pggan":
            image = generator(to_tensor(code))["image"]
        elif gan_type in ["stylegan", "stylegan2", "psp_stylegan2"]:
            image = generator.synthesis(to_tensor(code))["image"]
        else:
            raise ValueError(f"Unsupported GAN type `{gan_type}`.")
    return postprocess(image)[0]


def normalize(vector, eps=1e-12):
    norm = np.linalg.norm(vector.reshape(-1))
    if norm < eps:
        raise ValueError("Cannot normalize near-zero vector.")
    return vector / norm


def orthonormalize(vectors):
    """Orthonormalizes full latent-shaped directions."""

    basis = []
    for vector in vectors:
        work = vector.astype(np.float64).copy()
        for prev in basis:
            work -= np.sum(work * prev) * prev
        basis.append(normalize(work))
    return np.stack(basis, axis=0)


def semantic_directions(generator, gan_type, latent_shape, layer_idx,
                        semantic_id, num_directions):
    """Gets full latent-shaped SEFA directions starting at semantic_id."""

    layers, boundaries, values = factorize_weight(generator, layer_idx)
    order = np.argsort(np.real(values))[::-1]
    if semantic_id < 0 or semantic_id + num_directions > len(order):
        raise IndexError(
            f"semantic_id + num_directions must be <= {len(order)}, got "
            f"{semantic_id} + {num_directions}."
        )

    full = []
    chosen_values = []
    for idx in range(semantic_id, semantic_id + num_directions):
        boundary = np.real(boundaries[order[idx]]).astype(np.float64)
        if gan_type == "pggan" or len(latent_shape) == 1:
            direction = boundary.reshape(latent_shape)
        elif gan_type in ["stylegan", "stylegan2", "psp_stylegan2"]:
            direction = np.zeros(latent_shape, dtype=np.float64)
            direction[layers, :] = boundary
        else:
            raise ValueError(f"Unsupported GAN type `{gan_type}`.")
        full.append(direction)
        chosen_values.append(float(np.real(values[order[idx]])))
    return orthonormalize(full), layers, chosen_values


def default_weights(num_directions):
    """Deterministic semantic-axis weights for the scalar potential."""

    signs = np.array([1.0 if idx % 2 == 0 else -1.0 for idx in range(num_directions)])
    decay = 1.0 / (1.0 + np.arange(num_directions, dtype=np.float64))
    return signs * decay


def vector_field(current, origin, directions, weights, basis_name, order, scale):
    """Computes grad f(current) for the explicit basis scalar potential."""

    displacement = current - origin
    coords = np.array([np.sum(displacement * direction) for direction in directions])
    x = coords / float(scale)
    deriv = basis_derivative(basis_name, x, order) / float(scale)
    field = np.zeros_like(current, dtype=np.float64)
    for idx, direction in enumerate(directions):
        field += weights[idx] * deriv[idx] * direction
    return field, coords


def integrate_path(origin, directions, weights, basis_name, order,
                   scale, step_size, path_steps):
    """Builds a symmetric backward/origin/forward path from a vector field."""

    half_steps = path_steps // 2
    forward = []
    current = origin.astype(np.float64).copy()
    for _ in range(half_steps):
        field, _ = vector_field(current, origin, directions, weights,
                                basis_name, order, scale)
        current = current + step_size * field
        forward.append(current.copy())

    backward = []
    current = origin.astype(np.float64).copy()
    for _ in range(half_steps):
        field, _ = vector_field(current, origin, directions, weights,
                                basis_name, order, scale)
        current = current - step_size * field
        backward.append(current.copy())

    return list(reversed(backward)) + [origin.astype(np.float64)] + forward


def csv_fieldnames():
    return [
        "sample_id",
        "path_type",
        "basis_name",
        "basis_order",
        "semantic_id",
        "num_directions",
        "step_id",
        "image_mse_from_original",
        "image_ssim_from_original",
        "image_path",
    ]


def main():
    args = parse_args()
    os.environ["CUDA_VISIBLE_DEVICES"] = args.gpu_id
    os.makedirs(args.output_dir, exist_ok=True)

    unsupported = sorted(set(args.basis) - set(available_basis_names()))
    if unsupported:
        raise ValueError(f"Unsupported basis names: {unsupported}")
    if args.path_steps < 3 or args.path_steps % 2 == 0:
        raise ValueError("--path_steps must be an odd integer >= 3.")

    global torch, parse_gan_type, factorize_weight, load_generator, postprocess, to_tensor
    try:
        import torch as torch_module
        from utils import get_gan_type as parse_gan_type_func
        from utils import factorize_weight as factorize_weight_func
        from utils import load_generator as load_generator_func
        from utils import postprocess as postprocess_func
        from utils import to_tensor as to_tensor_func
    except ImportError as exc:
        raise ImportError("This experiment needs torch and the SEFA runtime dependencies.") from exc

    torch = torch_module
    parse_gan_type = parse_gan_type_func
    factorize_weight = factorize_weight_func
    load_generator = load_generator_func
    postprocess = postprocess_func
    to_tensor = to_tensor_func

    np.random.seed(args.seed)
    torch.manual_seed(args.seed)

    generator = load_generator(args.model)
    gan_type = parse_gan_type(generator)
    latents, latent_source = load_or_sample_latents(generator, gan_type, args)
    directions, layers, eigen_values = semantic_directions(
        generator,
        gan_type,
        latents[0].shape,
        args.layer_idx,
        args.semantic_id,
        args.num_directions,
    )
    weights = default_weights(args.num_directions)

    rows = []
    baseline_coeffs = np.linspace(-args.step_size, args.step_size, args.path_steps)
    for sample_id, latent in enumerate(latents):
        sample_dir = os.path.join(args.output_dir, f"sample_{sample_id:03d}")
        os.makedirs(sample_dir, exist_ok=True)
        original_image = decode_image(generator, gan_type, latent)
        save_image(original_image, os.path.join(sample_dir, "original.png"))

        all_items = []
        baseline_items = []
        for step_id, coeff in enumerate(baseline_coeffs):
            edited = latent.astype(np.float64) + coeff * directions[0]
            image = decode_image(generator, gan_type, edited)
            image_path = os.path.join(sample_dir, f"sefa_linear_{step_id:02d}.png")
            save_image(image, image_path)
            baseline_items.append((f"sefa {coeff:.2f}", image))
            all_items.append((f"sefa {coeff:.2f}", image))
            metrics = image_errors(original_image, image)
            rows.append({
                "sample_id": sample_id,
                "path_type": "sefa_linear",
                "basis_name": "",
                "basis_order": "",
                "semantic_id": args.semantic_id,
                "num_directions": args.num_directions,
                "step_id": step_id,
                "image_mse_from_original": metrics["image_mse"],
                "image_ssim_from_original": metrics["image_ssim"],
                "image_path": image_path,
            })
        make_comparison_grid(
            baseline_items,
            os.path.join(sample_dir, "sefa_linear_grid.png"),
            columns=args.path_steps,
        )

        for basis_name in args.basis:
            path = integrate_path(
                latent.astype(np.float64),
                directions,
                weights,
                basis_name,
                args.basis_order,
                args.projection_scale,
                args.step_size,
                args.path_steps,
            )
            basis_items = []
            for step_id, edited in enumerate(path):
                image = decode_image(generator, gan_type, edited)
                image_path = os.path.join(
                    sample_dir,
                    f"vector_field_{basis_name}_order{args.basis_order}_{step_id:02d}.png",
                )
                save_image(image, image_path)
                basis_items.append((f"{basis_name} {step_id}", image))
                all_items.append((f"{basis_name} {step_id}", image))
                metrics = image_errors(original_image, image)
                rows.append({
                    "sample_id": sample_id,
                    "path_type": "basis_vector_field",
                    "basis_name": basis_name,
                    "basis_order": args.basis_order,
                    "semantic_id": args.semantic_id,
                    "num_directions": args.num_directions,
                    "step_id": step_id,
                    "image_mse_from_original": metrics["image_mse"],
                    "image_ssim_from_original": metrics["image_ssim"],
                    "image_path": image_path,
                })
            make_comparison_grid(
                basis_items,
                os.path.join(sample_dir, f"vector_field_{basis_name}_grid.png"),
                columns=args.path_steps,
            )

        make_comparison_grid(
            all_items,
            os.path.join(sample_dir, "all_paths_grid.png"),
            columns=args.path_steps,
        )

    csv_path = os.path.join(args.output_dir, "results.csv")
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=csv_fieldnames())
        writer.writeheader()
        writer.writerows(rows)

    json_path = os.path.join(args.output_dir, "results.json")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump({
            "model": args.model,
            "gan_type": gan_type,
            "latent_source": latent_source,
            "semantic_id": args.semantic_id,
            "num_directions": args.num_directions,
            "layer_idx": args.layer_idx,
            "active_layers": layers,
            "eigen_values": eigen_values,
            "weights": weights.tolist(),
            "basis": args.basis,
            "basis_order": args.basis_order,
            "projection_scale": args.projection_scale,
            "step_size": args.step_size,
            "path_steps": args.path_steps,
            "results": rows,
        }, f, indent=2)

    print(f"Saved CSV: {csv_path}")
    print(f"Saved JSON: {json_path}")
    print(f"Saved vector-field images under: {args.output_dir}")


if __name__ == "__main__":
    main()
