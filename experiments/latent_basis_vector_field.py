"""Explicit-basis semantic vector-field traversal experiment.

This version makes the basis function participate in the semantic movement
itself. SEFA supplies several orthonormal semantic axes n_i, then an explicit
scalar potential is defined as

    f(z) = sum_i alpha_i * phi_order(<z - z0, n_i> / scale)

and the latent is moved by the gradient field

    z_{t+1} = z_t + step_size * grad f(z_t).

This is still training-free and explicit: the semantic path is generated by
analytical basis derivatives, not by an inverse network.

Example:
    python experiments/latent_basis_vector_field.py --num_samples 3 \
        --semantic_id 25 --num_directions 3 --basis legendre fourier \
        --basis_order 3 --path_steps 5 --output_dir results/basis_vector_field
"""

